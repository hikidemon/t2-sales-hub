def clean_text(val):
    if val is None:
        return None
    if isinstance(val, (int, float)):
        return val
    return str(val).strip()

def parse_number(val):
    if val is None or val == '':
        return 0.0
    if isinstance(val, (int, float)):
        return float(val)
    s = str(val).strip().replace(',', '.').replace(' ', '')
    try:
        return float(s)
    except (ValueError, TypeError):
        return 0.0

